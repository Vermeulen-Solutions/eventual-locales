#!/usr/bin/env node
// Used by each plugin's build. Sandbox bundles cannot import npm dependencies (the plugin CLI
// keeps `dependencies` external), so this vendors the message runtime into <outDir> and
// writes <outDir>/manifest.ts pinning the package version and every catalog hash for <namespace>.
//   eventual-locales-pack <namespace> <outDir>
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [namespace, outDir] = process.argv.slice(2);
if (!namespace || !outDir) {
  console.error("usage: eventual-locales-pack <namespace> <outDir>");
  process.exit(2);
}
const manifest = JSON.parse(readFileSync(new URL("../manifest.json", import.meta.url), "utf8"));
const hashes = manifest.namespaces[namespace];
if (!hashes) {
  console.error(`eventual-locales has no namespace "${namespace}"`);
  process.exit(1);
}
mkdirSync(outDir, { recursive: true });
const header = "// Generated by eventual-locales-pack from @vermeulen.solutions/eventual-locales. Do not edit.\n";
for (const file of ["format.mjs", "locale.mjs", "messages.mjs", "pack.mjs", "index.mjs", "index.d.mts"]) {
  const source = readFileSync(new URL(`../runtime/${file}`, import.meta.url), "utf8");
  writeFileSync(join(outDir, file), header + source);
}
const body = JSON.stringify({ package: manifest.package, version: manifest.version, namespace, hashes });
writeFileSync(join(outDir, "manifest.ts"), `${header}export default ${body};\n`);
console.log(`${outDir}: runtime + ${namespace} @ ${manifest.version}, ${Object.keys(hashes).length} languages`);
